// Helper to calculate relative ISO dates
const getOffsetDate = (days: number, hour: number, minute: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

